"""Trusted legacy snapshot relocation: no source data or replayed rewards."""
from copy import deepcopy
from pathlib import Path
import tempfile
import unittest

from game_server.catalog import DEMO_CATALOG, DomainError
from game_server.profile_cutover import import_complete_player
from game_server.service import GameService


class ProfileCutoverTests(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory()
        self.addCleanup(self.temp.cleanup)
        self.database = Path(self.temp.name) / 'public.sqlite'
        self.service = GameService(self.database, deepcopy(DEMO_CATALOG), clock=lambda: 1000000)
        self.other = self.service.create_player({'player_id': 'other', 'display_name': 'Other'})
        self.snapshot = GameService(Path(self.temp.name) / 'old-normalized.sqlite',
                                     deepcopy(DEMO_CATALOG), clock=lambda: 1000000).create_player(
                                         {'player_id': 'migrant', 'display_name': 'Earned Hero'})
        self.snapshot['wallet']['credits'] += 500
        self.snapshot['inventory']['earned-shard'] = 17
        self.snapshot['version'] = 8
        self.snapshot['guides'] = {}
        self.provenance = {'source_digest': 'a' * 64,
                           'source_sections': ['user', 'resources', 'inventory', 'roster',
                                               'missions', 'offers', 'operations'],
                           'section_map': {
                               'user': ['player_id', 'display_name', 'level', 'version', 'experience'],
                               'resources': ['wallet'], 'inventory': ['inventory'],
                               'roster': ['characters'], 'missions': ['missions'],
                               'offers': ['offer_purchases'], 'operations': ['legacy_receipts']},
                           'used_command_keys': ['old-grant', 'old-battle']}
        # This synthetic source was generated by GameService, not by the
        # original-profile translator. Inventory every generated neutral field.
        mapped = {field for fields in self.provenance['section_map'].values()
                  for field in fields}
        unmapped = sorted(set(self.snapshot) - mapped)
        if unmapped:
            self.provenance['source_sections'].append('generated-fields')
            self.provenance['section_map']['generated-fields'] = unmapped

    def cutover(self, snapshot=None, provenance=None):
        return import_complete_player(self.service,
            self.snapshot if snapshot is None else snapshot,
            self.provenance if provenance is None else provenance)

    def test_complete_trusted_snapshot_is_atomic_idempotent_and_preserves_balances(self):
        receipt = self.cutover()
        self.assertEqual(receipt['status'], 'imported')
        player = self.service.get_player('migrant')
        for field in self.snapshot:
            self.assertEqual(player[field], self.snapshot[field])
        self.assertEqual(player['legacy_cutover']['receipt_count'], 2)
        self.assertEqual(self.service.get_player('other'), self.other)
        self.assertEqual(self.cutover()['status'], 'already_imported')
        self.service = GameService(self.database, deepcopy(DEMO_CATALOG), clock=lambda: 1000001)
        self.assertEqual(self.cutover()['status'], 'already_imported')
        before = self.service.get_player('migrant')
        with self.assertRaises(DomainError) as blocked:
            self.service.execute('migrant', {'command': 'mission.begin',
                'idempotency_key': 'old-battle', 'parameters': {'mission_id': 'training.1', 'team': ['scout']}})
        self.assertEqual(blocked.exception.code, 'idempotency_conflict')
        self.assertEqual(self.service.get_player('migrant'), before)
        started = self.service.execute('migrant', {'command': 'mission.begin',
            'idempotency_key': 'fresh-battle',
            'parameters': {'mission_id': 'training.1', 'team': ['scout']}})
        self.assertEqual(started['battle']['status'], 'active')
        self.assertGreater(self.service.get_player('migrant')['version'], before['version'])

    def test_incomplete_provenance_invalid_fields_and_conflicts_rollback(self):
        cases = []
        for field, value in [('wallet', {'unmapped-currency': 42}), ('missions', {'unknown': {}}),
                             ('characters', {'unknown': {'level': 1, 'power': 1}}),
                             ('experience', 5000000), ('level', 2)]:
            bad = deepcopy(self.snapshot)
            bad[field] = value
            cases.append((bad, self.provenance))
        bad = deepcopy(self.snapshot)
        bad['wallet'] = {}
        cases.append((bad, self.provenance))
        bad = deepcopy(self.snapshot)
        del bad['inventory']
        cases.append((bad, self.provenance))
        bad = deepcopy(self.snapshot)
        bad['roster'] = {'native_hero': {'loyalty': 7}}
        cases.append((bad, self.provenance))
        manifest = deepcopy(self.provenance)
        manifest['section_map'].pop('roster')
        cases.append((self.snapshot, manifest))
        manifest = deepcopy(self.provenance)
        manifest['used_command_keys'] *= 2
        cases.append((self.snapshot, manifest))
        for snapshot, provenance in cases:
            with self.subTest(snapshot=snapshot, provenance=provenance):
                with self.assertRaises(DomainError):
                    self.cutover(snapshot, provenance)
                with self.assertRaises(DomainError) as missing:
                    self.service.get_player('migrant')
                self.assertEqual(missing.exception.code, 'player_not_found')
                self.assertEqual(self.service.get_player('other'), self.other)
        self.cutover()
        before = self.service.get_player('migrant')
        conflicting = deepcopy(self.snapshot)
        conflicting['inventory']['earned-shard'] += 1
        with self.assertRaises(DomainError):
            self.cutover(conflicting)
        self.assertEqual(self.service.get_player('migrant'), before)

    def test_cutover_refuses_existing_active_public_account(self):
        self.service.create_player({'player_id': 'migrant', 'display_name': 'Existing'})
        with self.assertRaises(DomainError) as problem:
            self.cutover()
        self.assertEqual(problem.exception.code, 'cutover_conflict')
        self.assertEqual(self.service.get_player('migrant')['display_name'], 'Existing')

    def test_manifest_must_match_all_normalized_snapshot_fields(self):
        self.assertIn('guides', self.snapshot)
        missing = deepcopy(self.provenance)
        for fields in missing['section_map'].values():
            if 'guides' in fields:
                fields.remove('guides')
        with self.assertRaises(DomainError) as incomplete:
            self.cutover(provenance=missing)
        self.assertEqual(incomplete.exception.code, 'cutover_incomplete')

        invented = deepcopy(self.provenance)
        self.assertNotIn('pass_sources', self.snapshot)
        invented['section_map']['generated-fields'].append('pass_sources')
        with self.assertRaises(DomainError) as unjustified:
            self.cutover(provenance=invented)
        self.assertEqual(unjustified.exception.code, 'cutover_incomplete')

        not_mapped = deepcopy(self.snapshot)
        not_mapped['pass_sources'] = {}
        with self.assertRaises(DomainError) as omitted:
            self.cutover(snapshot=not_mapped)
        self.assertEqual(omitted.exception.code, 'cutover_incomplete')
        self.assertEqual(self.cutover()['status'], 'imported')

    def test_historic_shop_stock_cannot_be_reset_or_imported_under_wrong_policy(self):
        catalog = deepcopy(DEMO_CATALOG)
        catalog['offers']['training-kit']['reset_policy'] = 'utc_day_once'
        catalog['offers']['training-kit']['purchase_limit'] = 10
        self.service = GameService(Path(self.temp.name) / 'daily.sqlite', catalog,
                                   clock=lambda: 16 * 86400 + 30)
        correct = deepcopy(self.snapshot)
        correct['offer_purchases'] = {}
        correct['offer_daily_purchases'] = {'training-kit': {'day': 16, 'count': 2}}
        manifest = deepcopy(self.provenance)
        manifest['section_map'].setdefault('generated-fields', []).append('offer_daily_purchases')
        invalid = []
        for value in (0, 11, True, -1, '2'):
            candidate = deepcopy(correct)
            candidate['offer_daily_purchases']['training-kit']['count'] = value
            invalid.append(candidate)
        for value in (-1, 17, True, '16'):
            candidate = deepcopy(correct)
            candidate['offer_daily_purchases']['training-kit']['day'] = value
            invalid.append(candidate)
        for key, row in (('unknown', {'day': 16, 'count': 1}),
                         ('training-kit', {'day': 16, 'count': 2, 'extra': True}),
                         ('training-kit', {'count': 2})):
            candidate = deepcopy(correct)
            candidate['offer_daily_purchases'] = {key: row}
            invalid.append(candidate)
        wrong_type = deepcopy(correct)
        wrong_type['offer_daily_purchases'] = []
        invalid.append(wrong_type)
        for candidate in invalid:
            with self.subTest(stock=candidate['offer_daily_purchases']):
                with self.assertRaises(DomainError):
                    import_complete_player(self.service, candidate, manifest)
                with self.assertRaises(DomainError):
                    self.service.get_player('migrant')
        lifetime = deepcopy(correct)
        lifetime['offer_purchases'] = {'training-kit': 2}
        with self.assertRaises(DomainError):
            import_complete_player(self.service, lifetime, manifest)

        imported = import_complete_player(self.service, correct, manifest)
        self.assertEqual(imported['status'], 'imported')
        saved = self.service.get_player('migrant')
        self.assertEqual(saved['offer_daily_purchases']['training-kit'], {'day': 16, 'count': 2})
        with self.assertRaises(DomainError) as denied:
            self.service.execute('migrant', {'command': 'shop.purchase',
                'idempotency_key': 'new-nonce',
                'parameters': {'offer_id': 'training-kit', 'quantity': 1}})
        self.assertEqual(denied.exception.code, 'purchase_limit')
        self.assertEqual(self.service.get_player('migrant'), saved)
        self.assertEqual(import_complete_player(self.service, correct, manifest)['status'], 'already_imported')
        self.service.clock = lambda: 17 * 86400 + 30
        bought = self.service.execute('migrant', {'command': 'shop.purchase',
            'idempotency_key': 'tomorrow',
            'parameters': {'offer_id': 'training-kit', 'quantity': 1}})
        self.assertEqual(bought['player']['offer_daily_purchases']['training-kit'],
                         {'day': 17, 'count': 1})

    def test_historic_permanent_purchase_count_stays_bounded(self):
        for count in (0, True, -1, 3, '1'):
            candidate = deepcopy(self.snapshot)
            candidate['offer_purchases'] = {'training-kit': count}
            with self.subTest(count=count), self.assertRaises(DomainError):
                self.cutover(snapshot=candidate)
        candidate = deepcopy(self.snapshot)
        candidate['offer_purchases'] = {'training-kit': 1}
        self.assertEqual(self.cutover(snapshot=candidate)['status'], 'imported')

    def test_imported_mission_clear_cannot_regrant_first_clear_reward(self):
        earned = deepcopy(self.snapshot)
        earned['missions'] = {'training.1': {'best_stars': 3, 'wins': 1}}
        self.assertEqual(self.cutover(snapshot=earned)['status'], 'imported')
        initial = self.service.get_player('migrant')
        self.assertNotIn('badge', initial['inventory'])
        started = self.service.execute('migrant', {'command': 'mission.begin',
            'idempotency_key': 'begin-after-cutover',
            'parameters': {'mission_id': 'training.1', 'team': ['scout']}})
        completed = self.service.execute('migrant', {'command': 'mission.complete',
            'idempotency_key': 'win-after-cutover',
            'parameters': {'battle_id': started['battle']['battle_id'],
                           'mission_id': 'training.1', 'outcome': 'victory', 'stars': 3}})
        self.assertEqual(completed['player']['missions']['training.1'],
                         {'best_stars': 3, 'wins': 2})
        self.assertNotIn('badge', completed['player']['inventory'])
        self.assertEqual(completed['player']['wallet']['credits'],
                         initial['wallet']['credits'] + 5)
        self.assertEqual(completed['player']['wallet']['energy'],
                         initial['wallet']['energy'] - 2)
        swept = self.service.execute('migrant', {'command': 'mission.sweep',
            'idempotency_key': 'sweep-after-cutover',
            'parameters': {'mission_id': 'training.1', 'quantity': 1}})
        self.assertEqual(swept['player']['missions']['training.1'],
                         {'best_stars': 3, 'wins': 3})
        self.assertNotIn('badge', swept['player']['inventory'])
        next_node = self.service.execute('migrant', {'command': 'mission.begin',
            'idempotency_key': 'next-node-after-cutover',
            'parameters': {'mission_id': 'training.2', 'team': ['scout']}})
        self.assertEqual(next_node['battle']['mission_id'], 'training.2')

    def test_imported_incomplete_mission_receipts_cannot_reenable_first_clear(self):
        for progress in ({'best_stars': 3}, {'wins': 1},
                         {'best_stars': 3, 'wins': 0},
                         {'best_stars': 0, 'wins': 1},
                         {'best_stars': 3, 'wins': True},
                         {'best_stars': 4, 'wins': 1},
                         {'best_stars': 3, 'wins': 1, 'nativeStar': 7},
                         {'best_stars': 3, 'wins': '1'}):
            candidate = deepcopy(self.snapshot)
            candidate['missions'] = {'training.1': progress}
            with self.subTest(progress=progress), self.assertRaises(DomainError):
                self.cutover(snapshot=candidate)
            with self.assertRaises(DomainError):
                self.service.get_player('migrant')


if __name__ == '__main__':
    unittest.main()
